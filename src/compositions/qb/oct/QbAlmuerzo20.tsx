/**
 * Las dos serif posibles para la cifra, con su métrica medida (fontTools):
 *   · bodoni — Bodoni Moda (libre, OFL): la más parecida a la referencia (Didot alta y de
 *     mucho contraste). ⚠️ NO es fuente de QB: va como propuesta y la decide Eli.
 *   · bell — Bell MT, la serif de QB: sus cifras son bajas (0,53 em) y con rulo.
 *     ⚠️ 02-10: en el still de prueba Chrome NO la usó (salió la serif de reemplazo del
 *     sistema). Antes de usar Bell MT en una cifra, verificar que cargue.
 * alto = alto del dígito · tinta = [inicio, fin] de «20» · base = línea base con interlínea 1.
 */
const SERIF = {
  bodoni: {familia: "BodoniModaQB", alto: 0.76, tinta: [0.04, 1.1295], base: 0.8625,
    extra: {fontVariationSettings: '"opsz" 28, "wght" 500'} as React.CSSProperties},
  bell: {familia: "BellMT", alto: 0.53, tinta: [0.047, 0.972], base: 0.7854, extra: {} as React.CSSProperties},
} as const;
export type SerifCifra = keyof typeof SERIF;

let bodoniLista = false;
const cargarBodoni = () => {
  if (bodoniLista || typeof document === "undefined") return;
  bodoniLista = true;
  const st = document.createElement("style");
  st.textContent = `@font-face { font-family: 'BodoniModaQB'; src: url('${staticFile("assets/fonts/BodoniModa.ttf")}') format('truetype'); font-weight: 400 900; font-display: block; }`;
  document.head.appendChild(st);
};
cargarBodoni();

/**
 * El descuento como en la referencia: «20» enorme en serif y, al costado, «DCTO. %» girado
 * 90° (se lee de abajo hacia arriba), del alto exacto de la cifra. `top` = tope de la cifra;
 * `alto` = alto de la cifra en px (el cuerpo sale de ahí).
 */
const Descuento: React.FC<{top: number; alto: number; serif: SerifCifra}> = ({top, alto: H, serif}) => {
  const F = SERIF[serif];
  // ⚠️ La serif sólo se usa en estos dos dígitos: hay que esperarla, o el still sale con la
  // serif de reemplazo del sistema (pasó en la primera prueba: dígitos de otra altura).
  const [espera] = React.useState(() => delayRender("serif de la cifra"));
  React.useEffect(() => {
    document.fonts.load(`500 100px ${F.familia}`, "20").then((caras) => {
      if (!caras.length) console.warn(`[QB] no cargó ${F.familia}`);
      continueRender(espera);
    }, () => continueRender(espera));
  }, [espera, F.familia]);
  const C = H / F.alto;
  const ancho20 = (F.tinta[1] - F.tinta[0]) * C;
  const s1 = 0.2 * H, s2 = 0.3 * H, aire = 0.06 * H;
  const total = ancho20 + aire + s2 * 0.86;
  return (
    <div style={{position: "absolute", top, left: (MESA.w - total) / 2, width: total, height: H, color: BLANCO,
      whiteSpace: "nowrap", lineHeight: 1}}>
      <div style={{position: "absolute", left: -F.tinta[0] * C, top: -(F.base - F.alto) * C, fontFamily: F.familia,
        fontSize: C, textShadow: "0 3px 28px rgba(0,0,0,0.4)", ...F.extra}}>{d.cifra}</div>
      <div style={{position: "absolute", left: ancho20 + aire, top: H, width: H, height: s2, transformOrigin: "0 0",
        transform: "rotate(-90deg)", display: "flex", justifyContent: "space-between", alignItems: "baseline",
        fontFamily: "Raleway", ...QB_CIFRAS}}>
        <span style={{fontSize: s1, fontWeight: 500, letterSpacing: "0.1em"}}>{d.dcto}</span>
        <span style={{fontSize: s2, fontWeight: 400}}>{d.signo}</span>
      </div>
    </div>
  );
};

